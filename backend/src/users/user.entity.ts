import { Column, CreateDateColumn, Entity, PrimaryGeneratedColumn } from 'typeorm';

@Entity({ name: 'users' })
export class User {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  /** Always stored lowercased + trimmed, so "Ana@X.com" and "ana@x.com" are one account. */
  @Column({ type: 'varchar', length: 254, unique: true })
  email: string;

  /** bcrypt hash — the plain password is never stored or logged. */
  @Column({ name: 'password_hash', type: 'varchar', length: 100, select: false })
  passwordHash: string;

  /**
   * Random id in the public status page URL (/status/<slug>). Generated by the
   * database default; can be rotated if a link leaks (POST /status-page/rotate).
   */
  @Column({
    name: 'status_slug',
    type: 'varchar',
    length: 32,
    unique: true,
    default: () => 'substr(md5(random()::text || clock_timestamp()::text), 1, 12)',
  })
  statusSlug: string;

  /** Heading on the public status page; null = a generic default. */
  @Column({ name: 'status_page_title', type: 'varchar', length: 80, nullable: true })
  statusPageTitle: string | null;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt: Date;
}
